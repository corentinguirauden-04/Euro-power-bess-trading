"""Simulation engine coupling European power market data with a BESS asset.

Manages the 15-minute simulation loop, dispatch order execution, State of Charge
tracking, cashflow settlement, degradation accounting, and performance reporting.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
from typing import Callable, Optional

import numpy as np
import pandas as pd

from src.asset import BatteryAsset


REQUIRED_MARKET_COLUMNS: tuple[str, ...] = (
    "timestamp",
    "demand_mw",
    "solar_mw",
    "wind_mw",
    "net_load_mw",
    "price_eur_mwh",
)


@dataclass(frozen=True)
class StepResult:
    """Execution record for a single 15-minute trading interval.

    Attributes:
        step_index: Zero-based time step index.
        timestamp: UTC timestamp of the interval start.
        price_eur_mwh: Spot clearing price in EUR/MWh.
        requested_power_mw: Requested dispatch power in MW (+ discharge, - charge).
        actual_power_mw: Realized average grid power in MW after physical constraints.
        energy_exchanged_mwh: Actual signed energy exchanged with grid in MWh.
        soc_before: Battery State of Charge before dispatch.
        soc_after: Battery State of Charge after dispatch.
        cashflow_eur: Instantaneous market settlement cashflow in EUR.
        degradation_cost_eur: Cycling wear cost incurred in this interval in EUR.
        net_pnl_eur: Net interval PnL (cashflow - degradation) in EUR.
        cumulative_pnl_eur: Running cumulative net PnL in EUR.
        done: True if the end of the simulation horizon has been reached.
    """

    step_index: int
    timestamp: pd.Timestamp
    price_eur_mwh: float
    requested_power_mw: float
    actual_power_mw: float
    energy_exchanged_mwh: float
    soc_before: float
    soc_after: float
    cashflow_eur: float
    degradation_cost_eur: float
    net_pnl_eur: float
    cumulative_pnl_eur: float
    done: bool


class TradingEnv:
    """Discrete-time BESS power trading environment.

    Couples a simulated (or historical) 15-minute market price series with a
    :class:`BatteryAsset`, executing dispatch decisions and tracking cashflows,
    degradation costs, and cumulative PnL.
    """

    def __init__(
        self,
        market_data: pd.DataFrame,
        battery: BatteryAsset,
        dt_hours: Optional[float] = None,
    ) -> None:
        """Initialize the trading environment.

        Args:
            market_data: DataFrame generated by ``PowerMarketSimulator.simulate``.
            battery: Physical BESS asset instance.
            dt_hours: Interval duration in hours. If omitted, inferred from
                ``market_data['timestamp']`` (defaults to 0.25 if length < 2).
        """
        missing = [col for col in REQUIRED_MARKET_COLUMNS if col not in market_data.columns]
        if missing:
            raise ValueError(f"market_data is missing required columns: {missing}")
        if market_data.empty:
            raise ValueError("market_data must contain at least one row.")

        self.market_data: pd.DataFrame = market_data.reset_index(drop=True).copy()
        self.battery: BatteryAsset = battery
        self.dt_hours: float = (
            float(dt_hours) if dt_hours is not None else self._infer_dt_hours(self.market_data)
        )
        if self.dt_hours <= 0.0:
            raise ValueError(f"dt_hours must be positive, got {self.dt_hours}.")

        self._current_step: int = 0
        self._cumulative_pnl_eur: float = 0.0
        self._history: list[StepResult] = []

    @staticmethod
    def _infer_dt_hours(df: pd.DataFrame) -> float:
        """Infer time step duration in hours from consecutive timestamps."""
        if len(df) < 2:
            return 0.25
        delta = pd.Timestamp(df.loc[1, "timestamp"]) - pd.Timestamp(df.loc[0, "timestamp"])
        return delta.total_seconds() / 3600.0

    @property
    def n_steps(self) -> int:
        """Total number of time intervals in the horizon."""
        return len(self.market_data)

    @property
    def current_step(self) -> int:
        """Index of the next interval to execute."""
        return self._current_step

    @property
    def is_done(self) -> bool:
        """Whether all intervals in the horizon have been executed."""
        return self._current_step >= self.n_steps

    @property
    def cumulative_pnl_eur(self) -> float:
        """Current cumulative net PnL in EUR."""
        return self._cumulative_pnl_eur

    def reset(self, initial_soc: Optional[float] = None) -> pd.Series:
        """Reset environment state, battery SoC, and trade ledger.

        Args:
            initial_soc: Optional starting SoC override.

        Returns:
            First market observation row as a pandas Series.
        """
        self.battery.reset(initial_soc=initial_soc)
        self._current_step = 0
        self._cumulative_pnl_eur = 0.0
        self._history.clear()
        return self.market_data.iloc[0]

    def step(self, power_mw: float) -> StepResult:
        """Execute one 15-minute trading interval.

        Args:
            power_mw: Requested dispatch power in MW. Positive = discharge/sell
                to grid; negative = charge/buy from grid.

        Returns:
            :class:`StepResult` containing physical execution and financial PnL.
        """
        if self.is_done:
            raise RuntimeError(
                "Simulation horizon is complete. Call reset() before stepping again."
            )

        row = self.market_data.iloc[self._current_step]
        timestamp = pd.Timestamp(row["timestamp"])
        price = float(row["price_eur_mwh"])

        soc_before = self.battery.soc
        energy_exchanged_mwh, soc_after = self.battery.step(power_mw, dt=self.dt_hours)
        actual_power_mw = energy_exchanged_mwh / self.dt_hours

        # Cashflow: exporting (+MWh) earns price; importing (-MWh) pays price
        # (and naturally earns revenue when Spot prices turn negative).
        cashflow_eur = energy_exchanged_mwh * price
        degradation_cost_eur = self.battery.compute_degradation_cost(energy_exchanged_mwh)
        net_pnl_eur = cashflow_eur - degradation_cost_eur
        self._cumulative_pnl_eur += net_pnl_eur

        step_index = self._current_step
        self._current_step += 1
        done = self.is_done

        result = StepResult(
            step_index=step_index,
            timestamp=timestamp,
            price_eur_mwh=price,
            requested_power_mw=float(power_mw),
            actual_power_mw=actual_power_mw,
            energy_exchanged_mwh=energy_exchanged_mwh,
            soc_before=soc_before,
            soc_after=soc_after,
            cashflow_eur=cashflow_eur,
            degradation_cost_eur=degradation_cost_eur,
            net_pnl_eur=net_pnl_eur,
            cumulative_pnl_eur=self._cumulative_pnl_eur,
            done=done,
        )
        self._history.append(result)
        return result

    def run_strategy(
        self,
        policy: Callable[[pd.Series, float], float],
        initial_soc: Optional[float] = None,
    ) -> pd.DataFrame:
        """Run a callable trading policy across the entire simulation horizon.

        Args:
            policy: Callable taking ``(market_row, current_soc)`` and returning
                requested dispatch power in MW.
            initial_soc: Optional starting SoC override.

        Returns:
            Full merged DataFrame combining market fundamentals and BESS execution.
        """
        self.reset(initial_soc=initial_soc)
        while not self.is_done:
            row = self.market_data.iloc[self._current_step]
            requested_power_mw = policy(row, self.battery.soc)
            self.step(requested_power_mw)
        return self.get_results_dataframe()

    def get_history(self) -> pd.DataFrame:
        """Return the step-by-step execution ledger as a pandas DataFrame."""
        if not self._history:
            return pd.DataFrame()
        return pd.DataFrame([asdict(entry) for entry in self._history])

    def get_results_dataframe(self) -> pd.DataFrame:
        """Return market data merged with BESS execution and PnL history."""
        history_df = self.get_history()
        if history_df.empty:
            return self.market_data.copy()

        exec_cols = [
            "requested_power_mw",
            "actual_power_mw",
            "energy_exchanged_mwh",
            "soc_before",
            "soc_after",
            "cashflow_eur",
            "degradation_cost_eur",
            "net_pnl_eur",
            "cumulative_pnl_eur",
        ]
        n = len(history_df)
        merged = self.market_data.iloc[:n].reset_index(drop=True).copy()
        for col in exec_cols:
            merged[col] = history_df[col].to_numpy()
        return merged

    def get_summary(self) -> dict[str, float]:
        """Compute key trading and operational KPIs for the completed run."""
        history = self.get_history()
        if history.empty:
            return {
                "total_pnl_eur": 0.0,
                "gross_cashflow_eur": 0.0,
                "total_degradation_eur": 0.0,
                "energy_charged_mwh": 0.0,
                "energy_discharged_mwh": 0.0,
                "equivalent_full_cycles": 0.0,
                "avg_charge_price_eur_mwh": float("nan"),
                "avg_discharge_price_eur_mwh": float("nan"),
                "final_soc": self.battery.soc,
            }

        charged_mask = history["energy_exchanged_mwh"] < 0.0
        discharged_mask = history["energy_exchanged_mwh"] > 0.0

        energy_charged_mwh = float((-history.loc[charged_mask, "energy_exchanged_mwh"]).sum())
        energy_discharged_mwh = float(history.loc[discharged_mask, "energy_exchanged_mwh"].sum())

        usable_capacity = self.battery.capacity_mwh * (self.battery.soc_max - self.battery.soc_min)
        equivalent_full_cycles = (
            0.5 * (energy_charged_mwh + energy_discharged_mwh) / usable_capacity
            if usable_capacity > 0.0
            else 0.0
        )

        avg_charge_price = (
            float(
                np.average(
                    history.loc[charged_mask, "price_eur_mwh"],
                    weights=-history.loc[charged_mask, "energy_exchanged_mwh"],
                )
            )
            if energy_charged_mwh > 0.0
            else float("nan")
        )
        avg_discharge_price = (
            float(
                np.average(
                    history.loc[discharged_mask, "price_eur_mwh"],
                    weights=history.loc[discharged_mask, "energy_exchanged_mwh"],
                )
            )
            if energy_discharged_mwh > 0.0
            else float("nan")
        )

        return {
            "total_pnl_eur": float(history["net_pnl_eur"].sum()),
            "gross_cashflow_eur": float(history["cashflow_eur"].sum()),
            "total_degradation_eur": float(history["degradation_cost_eur"].sum()),
            "energy_charged_mwh": energy_charged_mwh,
            "energy_discharged_mwh": energy_discharged_mwh,
            "equivalent_full_cycles": float(equivalent_full_cycles),
            "avg_charge_price_eur_mwh": avg_charge_price,
            "avg_discharge_price_eur_mwh": avg_discharge_price,
            "final_soc": float(history["soc_after"].iloc[-1]),
        }
